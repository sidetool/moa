import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import { verificationPath } from './verification-path.mjs';

const { chromium } = createRequire(import.meta.url)(process.env.MOA_PLAYWRIGHT_PATH || 'playwright-core');
process.env.VITE_MOCK = '0';
const web = await createServer({ root: fileURLToPath(new URL('..', import.meta.url)), logLevel: 'error', plugins: [{ name: 'auth-fixture', transformIndexHtml: html => html.replace('<head>', '<head><meta name="moa-auth" content="enabled">') }], server: { port: 0, open: false, hmr: false } });
await web.listen();
const browser = await chromium.launch({ executablePath: process.env.MOA_BROWSER_EXECUTABLE });
const base = web.resolvedUrls.local[0], errors = [];
const permissions = ['video.watch', 'subtitles.add', 'subtitles.translate'];
try {
  for (const width of [1280, 390]) {
    const context = await browser.newContext({ viewport: { width, height: 900 } });
    await context.addInitScript(() => { localStorage.setItem('moa.profile', 'p'); localStorage.setItem('moa.remoteMode', 'off'); });
    const changes = [], account = { id: 'member', username: 'member', role: 'member', permissions: [...permissions], disabled: false, createdAt: new Date().toISOString(), lastLoginAt: null, inviteLabel: null };
    let role = 'admin', pluginRequests = 0, emptySchema = false, showPluginData = false;
    await context.route(url => url.pathname.startsWith('/api/') || url.pathname.startsWith('/__moa/api/'), route => {
      const request = route.request(), path = new URL(request.url()).pathname;
      if (path === '/api/me') return route.fulfill({ json: { id: role, username: role, role, permissions } });
      if (path === '/api/profiles') return route.fulfill({ json: [{ id: 'p', name: '테스트', color: 'blue', kids: false }] });
      if (path === '/api/settings') return route.fulfill({ json: {} });
      if (path === '/api/sources') return route.fulfill({ json: [{ id: 'fixture', name: '필터 확인', installed: true, enabled: true, type: 'anime' }] });
      if (path === '/api/sources/fixture/filters') return route.fulfill({ json: { revision: emptySchema ? 'two' : 'one', availableModes: ['popular'], filters: emptySchema ? [] : [{ id: 'genre', label: '장르', position: 0, kind: 'select', options: ['전체', '액션'], defaultValue: 0 }, { id: 'sort', label: '정렬', position: 1, kind: 'sort', options: ['제목', '최신'], defaultValue: { index: 0, ascending: false } }, { id: 'dub', label: '더빙 포함', position: 2, kind: 'checkbox', defaultValue: false }] } });
      if (path === '/api/sources/fixture/browse') return route.fulfill({ json: { items: [], page: 1, hasNextPage: false } });
      if (path === '/api/plugins') { pluginRequests++; return route.fulfill({ json: showPluginData ? [{ id: 'fixture', name: '데이터 확인', version: '1.0.0', kind: 'script', apiVersion: 1, enabled: false, permissions: [], placements: ['settings'], connect: [] }] : [] }); }
      if (path === '/api/admin/plugins/fixture/data') return route.fulfill({ json: [{ profileId: 'p', profileName: '테스트', bytes: 13, value: { example: 1 } }] });
      if (path === '/__moa/api/accounts') return route.fulfill({ json: [account] });
      if (path === '/__moa/api/accounts/member' && request.method() === 'PATCH') {
        const body = request.postDataJSON(); changes.push(body); Object.assign(account, body);
        return route.fulfill({ status: 204 });
      }
      return route.fulfill({ json: [] });
    });
    const page = await context.newPage(); page.on('pageerror', error => errors.push(String(error)));
    await page.goto(base + 'accounts');
    await page.getByRole('button', { name: 'member 접속 기록 없음', exact: true }).click();
    const permissionMenu = page.getByRole('combobox', { name: 'member 권한', exact: true });
    await permissionMenu.click();
    const subtitles = page.getByRole('option', { name: '자막 추가', exact: true });
    assert.equal(await subtitles.getAttribute('aria-selected'), 'true');
    await subtitles.click();
    await page.locator('[role="option"][aria-selected="false"]:enabled').waitFor();
    assert.deepEqual(changes, [{ permissions: ['video.watch', 'subtitles.translate'] }]);
    assert.equal(await permissionMenu.getAttribute('aria-expanded'), 'true');
    assert.equal(await permissionMenu.evaluate(element => element === document.activeElement), true);
    await permissionMenu.press('End');
    await permissionMenu.press('Space');
    await page.getByRole('option', { name: '자막 번역', exact: true }).and(page.locator('[aria-selected="false"]:enabled')).waitFor();
    assert.deepEqual(changes.at(-1), { permissions: ['video.watch'] });
    await permissionMenu.press('Escape');
    assert.equal(await permissionMenu.getAttribute('aria-expanded'), 'false');
    await page.reload();
    await page.getByRole('button', { name: 'member 접속 기록 없음', exact: true }).click();
    await permissionMenu.click();
    assert.equal(await subtitles.getAttribute('aria-selected'), 'false');
    assert.equal(await page.getByRole('option', { name: '자막 번역', exact: true }).getAttribute('aria-selected'), 'false');
    await permissionMenu.press('Escape');
    await page.getByRole('button', { name: '관리자로 지정', exact: true }).click();
    const dialog = page.getByRole('alertdialog', { name: '관리자로 지정', exact: true });
    await dialog.waitFor();
    assert.equal(changes.length, 2);
    await dialog.getByRole('button', { name: '취소', exact: true }).click();
    assert.equal(await dialog.count(), 0); assert.equal(changes.length, 2);
    await page.getByRole('button', { name: '관리자로 지정', exact: true }).click();
    await page.screenshot({ path: verificationPath(`verification-account-confirm-${width}.png`), fullPage: true });
    await dialog.getByRole('button', { name: '지정', exact: true }).click();
    await page.getByRole('button', { name: '관리자 해제', exact: true }).waitFor();
    assert.deepEqual(changes.at(-1), { role: 'admin' });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.goto(base + 'sources/fixture');
    await page.getByText('필터와 정렬', { exact: true }).click();
    await page.getByRole('combobox', { name: '장르', exact: true }).click();
    await page.getByRole('option', { name: '액션', exact: true }).click();
    await page.getByRole('checkbox', { name: '더빙 포함', exact: true }).check();
    const reset = page.getByRole('button', { name: '초기화', exact: true }), apply = page.getByRole('button', { name: '조건 적용', exact: true });
    const resetBox = await reset.boundingBox(), applyBox = await apply.boundingBox();
    assert.equal(resetBox.y, applyBox.y);
    await apply.click();
    assert.equal(JSON.parse(new URL(page.url()).searchParams.get('filters')).filters.length, 2);
    const savedFilterUrl = page.url();
    await reset.click();
    assert.equal(await page.getByRole('checkbox', { name: '더빙 포함', exact: true }).isChecked(), false);
    await apply.click();
    assert.equal(new URL(page.url()).searchParams.has('filters'), false);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: verificationPath(`verification-source-filters-${width}.png`), fullPage: true });
    emptySchema = true;
    await page.goto(savedFilterUrl);
    await page.locator('.browse-filters summary').click();
    await page.getByText('이 소스는 추가 필터를 제공하지 않습니다.', { exact: true }).waitFor();
    await reset.click();
    await apply.click();
    assert.equal(new URL(page.url()).searchParams.has('filters'), false);
    await page.goto(base + 'settings#account');
    await page.getByRole('button', { name: /^비밀번호 변경/ }).click();
    const password = page.getByRole('dialog', { name: '비밀번호 변경', exact: true });
    const current = password.locator('input').first();
    await current.fill('local-test-password');
    await password.getByRole('button', { name: '비밀번호 보기', exact: true }).first().click();
    assert.equal(await current.getAttribute('type'), 'text');
    assert.equal(await current.inputValue(), 'local-test-password');
    await password.getByRole('button', { name: '비밀번호 숨기기', exact: true }).click();
    assert.equal(await current.getAttribute('type'), 'password');
    await password.getByRole('button', { name: '닫기', exact: true }).click();
    showPluginData = true;
    await page.goto(base + 'plugins');
    const viewData = page.getByRole('button', { name: '데이터 보기', exact: true });
    await viewData.click();
    const info = page.getByRole('alertdialog', { name: '데이터 확인 데이터', exact: true });
    await info.locator('summary').waitFor();
    assert.equal(await info.getByRole('button').count(), 1);
    await info.getByRole('button', { name: '닫기', exact: true }).press('Shift+Tab');
    assert.equal(await info.locator('summary').evaluate(element => element === document.activeElement), true);
    await info.locator('summary').press('Space');
    assert.equal(await info.locator('details[open]').count(), 1);
    await info.locator('summary').press('Escape');
    assert.equal(await info.count(), 0);
    assert.equal(await viewData.evaluate(element => element === document.activeElement), true);
    role = 'member'; pluginRequests = 0;
    await page.goto(base + 'plugins');
    await page.getByText('관리자만 볼 수 있어요', { exact: true }).waitFor();
    assert.equal(await page.locator('.plugin-row, .plugin-frame, .plugin-dialog').count(), 0);
    await page.goto(base + 'me');
    await page.getByRole('link', { name: '설정', exact: true }).waitFor();
    assert.equal(await page.getByRole('link', { name: '플러그인', exact: true }).count(), 0);
    if (width === 1280) {
      await page.getByRole('button', { name: '프로필 메뉴', exact: true }).click();
      assert.equal(await page.getByRole('menuitem', { name: '플러그인', exact: true }).count(), 0);
    }
    assert.equal(pluginRequests, 0);
    await page.screenshot({ path: verificationPath(`verification-member-menu-${width}.png`), fullPage: true });
    await context.close();
  }
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: true, widths: [1280, 390], errors }));
} finally { await browser.close(); await web.close(); }
